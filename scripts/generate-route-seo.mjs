import fs from 'node:fs'
import path from 'node:path'

const appDir = path.join(process.cwd(), 'app')
const skipPrefixes = ['app/admin', 'app/projects']

function walk(dir, base = 'app') {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  const files = []
  for (const e of entries) {
    const rel = path.join(base, e.name)
    const full = path.join(dir, e.name)
    if (e.isDirectory()) {
      if (skipPrefixes.some((p) => rel.startsWith(p))) continue
      files.push(...walk(full, rel))
    } else if (e.name === 'page.tsx') {
      files.push(full)
    }
  }
  return files
}

function routeFromFile(filePath) {
  const dir = path.relative(appDir, path.dirname(filePath)).replace(/\\/g, '/')
  if (!dir || dir === '.') return '/'
  return `/${dir}`
}

const TITLE_OVERRIDES = {
  '/why-berkshire-hathaway': 'Why My Brokerage Matters When You Sell a Tenant-Occupied Rental | Dr. Jan Duffy',
  '/berkshire-hathaway/comparison': 'How My Brokerage Compares | Dr. Jan Duffy',
}

function stripBhhs(text) {
  return text
    .replace(/\s*\|\s*Berkshire Hathaway HomeServices[^|]*/gi, '')
    .replace(/\s*Berkshire Hathaway HomeServices/gi, '')
    .replace(/\s*Berkshire Hathaway/gi, '')
    .replace(/\s*\|\s*BHHS[^|]*/gi, '')
    .replace(/\s*BHHS[^|]*/gi, '')
    .replace(/\s*-\s*Dr\. Janet Duffy/gi, '')
    .replace(/\s*Dr\. Janet Duffy\s*-\s*/gi, '')
    .replace(/\s+/g, ' ')
    .trim()
}

function extractH1(content) {
  const h1Match = content.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i)
  if (!h1Match) return null
  return h1Match[1]
    .replace(/<[^>]+>/g, '')
    .replace(/\{[^}]+\}/g, '')
    .replace(/&apos;/g, "'")
    .replace(/\s+/g, ' ')
    .trim()
}

function extractSubtitle(content) {
  const afterH1 = content.split(/<\/h1>/i)[1] ?? ''
  const pMatch = afterH1.match(/<p[^>]*className="[^"]*text-(?:xl|lg)[^"]*"[^>]*>([\s\S]*?)<\/p>/i)
  if (!pMatch) return null
  return pMatch[1]
    .replace(/<[^>]+>/g, '')
    .replace(/\{[^}]+\}/g, '')
    .replace(/&apos;/g, "'")
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 160)
}

function titleForRoute(route, h1) {
  if (TITLE_OVERRIDES[route]) {
    return TITLE_OVERRIDES[route]
  }
  if (route === '/') {
    return 'Selling a Las Vegas Rental with Tenants | Dr. Jan Duffy'
  }
  if (h1 && /30 days/i.test(h1)) {
    h1 = h1.replace(/From Failed to Sold in 30 Days/gi, 'From Failed to Sold — A Structured Relisting Plan')
  }
  const base = stripBhhs(h1 || humanizeRoute(route))
  if (base.toLowerCase().includes('dr. jan')) {
    return base
  }
  return `${base} | Dr. Jan Duffy`
}

function humanizeRoute(route) {
  const slug = route.split('/').filter(Boolean).pop() ?? 'home'
  return slug
    .split('-')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ')
}

const routes = {}
for (const file of walk(appDir)) {
  const content = fs.readFileSync(file, 'utf8')
  const route = routeFromFile(file)
  const h1 = extractH1(content)
  const subtitle = extractSubtitle(content)
  const title = titleForRoute(route, h1)
  const description =
    subtitle ||
    (route === '/'
      ? 'Sell a tenant-occupied rental in Las Vegas or Henderson. Dr. Jan Duffy helps landlords navigate NRS 118A notices, showings, and investor-ready marketing.'
      : `${stripBhhs(h1 || humanizeRoute(route))}. Las Vegas rental property sales guidance from Dr. Jan Duffy. Call (702) 222-1964.`)

  routes[route] = {
    title: stripBhhs(title),
    description: stripBhhs(description).slice(0, 320),
  }
}

const out = `// Generated by scripts/generate-route-seo.mjs — do not edit by hand
export type RouteSeo = { title: string; description: string }

export const ROUTE_SEO: Record<string, RouteSeo> = ${JSON.stringify(routes, null, 2)} as const
`

fs.writeFileSync(path.join(process.cwd(), 'lib/route-seo.ts'), out)
console.log(`Wrote ${Object.keys(routes).length} routes to lib/route-seo.ts`)
